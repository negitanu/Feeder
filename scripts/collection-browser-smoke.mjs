import {browserSession} from './browser-session.mjs';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const require=createRequire(new URL('../frontend/package.json',import.meta.url));
const {chromium}=require('@playwright/test');
const browser=await chromium.launch({headless:true});
try {
 const page=await browser.newPage({viewport:{width:1280,height:800}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const origin=process.env.FEEDER_URL||'http://127.0.0.1:8080';
 await browserSession(page,origin);
 await page.goto(origin);
 await page.getByRole('button',{name:'設定',exact:true}).click();
 await page.getByRole('textbox',{name:'フォルダー名',exact:true}).fill('検証フォルダー');
 await page.getByRole('button',{name:'作成',exact:true}).click();
 await page.getByRole('button',{name:'読む',exact:true}).click();
 await page.getByRole('button',{name:'テスト購読の操作',exact:true}).click();
 await page.getByRole('button',{name:'編集',exact:true}).click();
 await page.getByLabel('表示名',{exact:true}).fill('検証購読');
 await page.getByRole('dialog').getByRole('combobox').selectOption({label:'検証フォルダー'});
 await page.getByRole('button',{name:'保存',exact:true}).click();
 await page.getByRole('button',{name:'検証購読の操作',exact:true}).waitFor();
 await page.getByRole('button',{name:'検証フォルダーを折りたたむ',exact:true}).click();
 await page.reload();
 await page.getByRole('button',{name:'検証フォルダーを展開',exact:true}).waitFor();
 await page.getByRole('button',{name:/^▰ 検証フォルダー$/}).click();
 await page.getByRole('button',{name:'検証フォルダーを展開',exact:true}).waitFor();
 await page.getByRole('button',{name:'検証フォルダーを展開',exact:true}).click();
 await page.getByRole('button',{name:'検証購読の操作',exact:true}).click();
 await page.getByRole('button',{name:'一時停止',exact:true}).click();
 let library=await (await page.request.get(origin+'/api/library')).json();
 let feed=library.feeds.find(f=>f.title==='検証購読');assert.equal(feed.paused,true);
 assert.equal((await (await page.request.get(origin+`/api/articles?feed_id=${feed.id}`)).json()).total,18);
 assert.equal((await page.request.post(origin+`/api/feeds/${feed.id}/refresh`)).status(),409);
 await page.getByRole('button',{name:'検証購読の操作',exact:true}).click();
 await page.getByRole('button',{name:'再開',exact:true}).click();
 library=await (await page.request.get(origin+'/api/library')).json();assert.equal(library.feeds.find(f=>f.id===feed.id).paused,false);
 await page.getByRole('button',{name:'設定',exact:true}).click();
 await page.getByRole('textbox',{name:'サイトまたはフィード URL',exact:true}).fill('http://127.0.0.1:8080/private');
 const rejected=page.waitForResponse(r=>r.url().endsWith('/api/discover')&&r.request().method()==='POST');
 await page.getByRole('button',{name:'フィードを探す',exact:true}).click();
 assert.ok((await rejected).status()>=400);
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 await page.getByRole('button',{name:'読む',exact:true}).click();
 await page.getByRole('button',{name:'検証購読の操作',exact:true}).click();
 page.once('dialog',dialog=>dialog.accept());
 await page.getByRole('button',{name:'削除',exact:true}).click();
 await page.waitForFunction(()=>!document.querySelector('[aria-label="検証購読の操作"]'));
 assert.equal((await (await page.request.get(origin+'/api/articles')).json()).total,18);
 assert.deepEqual(errors,[]);
 console.log('Collection browser passed: folder create/move/collapse retention, pause/resume and article retention, private URL refusal, narrow layout.');
} finally {await browser.close();}
