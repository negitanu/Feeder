import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import { browserSession } from './browser-session.mjs'
const require = createRequire(new URL('../frontend/package.json', import.meta.url))
const { chromium } = require('@playwright/test')
const browser = await chromium.launch({ headless: true, ...(process.env.FEEDER_CHROMIUM_PATH ? { executablePath: process.env.FEEDER_CHROMIUM_PATH } : {}) })
const origin = process.env.FEEDER_URL || 'http://127.0.0.1:18771'
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } })
  await browserSession(page, origin)
  await page.goto(origin)
  await page.getByRole('button', { name: '設定', exact: true }).click()
  const input = page.getByLabel('設定JSONファイル')
  const data = { format: 'feeder-settings', format_version: 1, settings: { reader: { display_timezone: 'Asia/Tokyo', default_view: 'unread' }, collection: { enabled: true, interval_seconds: 600 }, api: { rate_limit: 80 }, folders: [{ name: 'Synthetic folder' }, { name: null }], subscriptions: [{ url: 'https://example.invalid/feed' }], presentation: {appearance:'dark',layout:'line',width:320,collapsed_folders:[]} } }
  const choose = async object => input.setInputFiles({ name: 'settings.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(object)) })
  const state = async () => (await page.request.get(origin + '/api/configuration/import')).json()
  const before = await state()
  await choose(data)
  await page.getByLabel('読み込みプレビュー').waitFor()
  assert.deepEqual(await state(), before)
  await page.getByRole('button', { name: 'キャンセル', exact: true }).click()
  assert.equal(await page.getByLabel('読み込みプレビュー').count(), 0)
  await choose(data)
  await page.getByLabel('読み込みプレビュー').waitFor()
  assert.ok((await page.getByLabel('読み込みプレビュー').innerText()).includes('省略 1 件'))
  await page.getByLabel('このブラウザーにも表示設定を適用', { exact: false }).check()
  const other = await page.request.patch(origin + '/api/collection/settings', { data: { enabled: false, interval_seconds: 1200 }, headers: { origin } })
  assert.equal(other.status(), 200)
  await page.getByRole('button', { name: '設定を適用', exact: true }).click()
  await page.getByRole('alert').filter({ hasText: 'プレビュー後' }).waitFor()
  const conflict = await state()
  assert.equal(conflict.reader.display_timezone, before.reader.display_timezone)
  assert.equal(conflict.collection.interval_seconds, 1200)
  assert.ok(!conflict.folders.includes('Synthetic folder'))
  assert.notEqual(await page.getByLabel('設定のテーマ').inputValue(), 'dark')
  await choose(data)
  assert.equal(await page.getByLabel('このブラウザーにも表示設定を適用', { exact: false }).isChecked(), false)
  await page.getByLabel('このブラウザーにも表示設定を適用', { exact: false }).check()
  await page.getByRole('button', { name: '設定を適用', exact: true }).click()
  await page.getByText('設定を読み込みました。', { exact: false }).waitFor()
  const after = await state()
  assert.equal(after.reader.display_timezone, 'Asia/Tokyo')
  assert.equal(after.collection.interval_seconds, 600)
  assert.equal(after.rate_limit, 80)
  assert.ok(after.folders.includes('Synthetic folder'))
  assert.equal(await page.getByLabel('設定のテーマ').inputValue(), 'dark')
  assert.equal(await page.getByLabel('設定の記事表示形式').inputValue(), 'line')
  await page.waitForFunction(() => localStorage.getItem('feeder-sidebar-width') === '320')
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  await choose({ ...data, settings: { ...data.settings, collection: { enabled: true, interval_seconds: 1 } } })
  await page.getByRole('alert').filter({ hasText: '正しくありません' }).waitFor()
  assert.deepEqual(await state(), after)
  const exported = await page.request.post(origin + '/api/configuration/export', { data: { presentation: { appearance: 'system', width: 250, layout: 'standard', collapsed_folders: [] } }, headers: { origin } })
  assert.equal(exported.status(), 200)
  await input.setInputFiles({ name: 'actual-export.json', mimeType: 'application/json', buffer: await exported.body() })
  await page.getByLabel('読み込みプレビュー').waitFor()
  await page.getByRole('button', { name: '設定を適用', exact: true }).click()
  await page.getByText('設定を読み込みました。', { exact: false }).waitFor()
  assert.deepEqual(await state(), after)
  console.log('settings import preview, cancellation, conflict, atomic apply, invalid, mobile: passed')
} finally { await browser.close() }
