import {browserSession} from './browser-session.mjs';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(new URL('../frontend/package.json',import.meta.url));
const {chromium}=require('@playwright/test');
const browser=await chromium.launch({headless:true});
try{
 const page=await browser.newPage({viewport:{width:1280,height:800}});
 const origin=process.env.FEEDER_URL||'http://127.0.0.1:8080';
 await browserSession(page,origin);
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const list=async(query='')=>(await(await page.request.get(origin+'/api/articles?limit=100'+query)).json());
 const initial=await list();assert.equal(initial.total,36,'Use a dedicated generated demo database');
 const ids=initial.items.map(a=>a.id);
 const reset=await page.request.post(origin+'/api/articles/bulk-state',{data:{ids,read:false,starred:false,filters:{}}});assert.equal(reset.status(),200);
 const beforeHistory=(await list('&history=true')).total;
 await page.goto(origin);await page.locator('.article-card').first().waitFor();
 assert.ok(await page.locator('.article-card').count()<36);
 await page.getByRole('button',{name:'全て既読',exact:true}).click();
 await page.waitForFunction(()=>document.querySelectorAll('.article-card.read').length>0);
 assert.equal((await list('&unread=true')).total,0);
 assert.equal((await list('&history=true')).total,beforeHistory);
 await page.request.post(origin+'/api/articles/bulk-state',{data:{ids,read:false,filters:{}}});
 await page.reload();await page.locator('summary').filter({hasText:'詳細検索'}).click();
 await page.getByRole('textbox',{name:'含まない',exact:true}).fill('サンプル記事 1');
 await page.getByRole('button',{name:'条件を適用',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('.result-count')?.textContent?.includes('25'));
 await page.getByRole('button',{name:'全て既読',exact:true}).click();
 await page.waitForFunction(()=>document.querySelectorAll('.article-card.read').length>0);
 const all=await list();assert.equal(all.items.filter(a=>a.is_read).length,25);assert.equal(all.items.filter(a=>!a.is_read).length,11);
 const selected=page.getByRole('checkbox',{name:/^記事を選択:/});await selected.nth(0).check();await selected.nth(1).check();
 await page.getByRole('button',{name:/選択.*スターを付ける/}).click();
 await page.waitForFunction(()=>document.querySelectorAll('.article-card .is-starred').length===2);
 const starIds=(await list('&starred=true')).items.map(a=>a.id);assert.equal(starIds.length,2);
 await page.locator('.load-sentinel').scrollIntoViewIfNeeded();
 await page.waitForFunction(()=>document.querySelectorAll('.article-card').length===25);
 await page.locator('.article-open').last().scrollIntoViewIfNeeded();
 const savedScroll=await page.evaluate(()=>window.scrollY);
 const title=await page.locator('.article-card strong').last().innerText();
 await page.locator('.article-open').last().click();await page.getByRole('heading',{name:title,exact:true}).waitFor();
 await page.getByRole('button',{name:/一覧に戻る/}).click();
 await page.waitForFunction(y=>Math.abs(window.scrollY-y)<2,savedScroll);
 assert.equal(await page.locator('.article-card').count(),25);
 assert.equal(await page.locator('input[aria-label^="記事を選択:"]:checked').count(),2);
 await page.getByRole('button',{name:/最近読んだ記事/}).click();await page.waitForFunction(expected=>document.querySelector('.article-card strong')?.textContent===expected,title);
 assert.equal(await page.locator('.article-card strong').first().innerText(),title);
 await page.reload();await page.getByRole('button',{name:/最近読んだ記事/}).click();await page.waitForFunction(expected=>document.querySelector('.article-card strong')?.textContent===expected,title);
 const historyBefore=(await list('&history=true')).total;
 const out=await page.request.post(origin+'/api/articles/bulk-state',{data:{ids:[ids[0],999999],read:false,filters:{}}});assert.ok(out.status()>=400);
 assert.equal((await list('&history=true')).total,historyBefore);
 await page.setViewportSize({width:390,height:844});await page.locator('summary').filter({hasText:'詳細検索'}).click();
 await page.getByRole('textbox',{name:'含まない',exact:true}).fill('"');
 await page.getByRole('button',{name:'条件を適用',exact:true}).click();await page.getByRole('alert').waitFor();
 assert.equal(await page.getByRole('button',{name:'全て既読',exact:true}).isDisabled(),true);
 await page.getByRole('button',{name:'詳細条件をクリア',exact:true}).click();await page.waitForFunction(expected=>document.querySelector('.article-card strong')?.textContent===expected,title);
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 assert.deepEqual(errors,[]);
 console.log('Productivity browser passed: unloaded scoped all-read, unchanged history, detailed exclusions, selected stars, history persistence and mobile.');
}finally{await browser.close();}
